const FORWARD_WORDS = [
  "а", "без", "близ", "в", "во", "вместо", "вокруг", "для", "до", "за", "зато", "и", "из", "из-за", "из-под", "или", "к", "как", "ко", "кроме", "либо", "между", "на", "над", "не", "ни", "но", "о", "об", "обо", "около", "от", "перед", "по", "под", "при", "про", "ради", "с", "сквозь", "со", "среди", "у", "через", "что"
];

const escapedForwardWords = FORWARD_WORDS
  .sort((a, b) => b.length - a.length)
  .map((word) => word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));

const forwardRx = new RegExp(
  `(^|[\\s([{\"«„'])(${escapedForwardWords.join("|")})[\\t\\n\\r ]+(?=[\\p{L}\\p{N}€$£«„\"'(])`,
  "giu"
);

function protectRussianWraps(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || parent.closest("script, style, code, pre, [data-no-typograph]")) return NodeFilter.FILTER_REJECT;
      return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
    }
  });

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  for (const node of nodes) {
    let value = node.nodeValue;
    let previous;
    do {
      previous = value;
      value = value.replace(forwardRx, "$1$2\u00A0");
    } while (value !== previous);

    node.nodeValue = value
      .replace(/(?<=[\p{L}\p{N}]) +(?=(?:бы|же|ли)\b)/giu, "\u00A0")
      .replace(/(\d) +(?=(?:%|шт\.?|кг|г|млн|тыс\.?|лет|месяц(?:ев|а)?|дн(?:ей|я)|недел(?:ь|и|ю)|заказ(?:ов|а)?|отзыв(?:ов|а)?|рынк(?:ов|а)?|источник(?:ов|а)?|единиц(?:а|ы)?|карточ(?:ек|ки)|короб(?:ок|ки)|пар(?:ы)?|МСП)\b)/giu, "$1\u00A0")
      .replace(/(?<=\d) +(?=\d{3}(?:\D|$))/g, "\u202F");
  }
}

